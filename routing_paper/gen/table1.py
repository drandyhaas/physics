#!/usr/bin/env python3
"""table1.py -- Table I of the paper, from the grades baseline_ladders.py wrote.

  python3 gen/table1.py [OUTROOT]

With OUTROOT (baseline_ladders.py's, each rung's grade in OUTROOT/MODE_TAG/result.json), the grades are copied into
data/table1/MODE_TAG.json first; without it, the table is written from data/table1 alone. Writes figs/table1.tex (the
tabular's body, \\input by main.tex) and refuses a rung any of the four routers has no grade for, so the paper cannot
quote a cell no run produced. The Zynq's last row, 'Full', is its bus on its own board, from data/board (gen/board_bus.py).
"""
import json
import os
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
DATA = os.path.join(ROOT, 'data', 'table1')
MODES = ('ours', 'krt', 'fr', 'human')
LADDERS = (('h3', 'Allwinner H3 to DDR3', (15, 28, 35, 41, 51)),
           ('zynq', 'Zynq-7020 to DDR3', (18, 26, 33, 38, 43)))


def main():
    if len(sys.argv) > 1:
        os.makedirs(DATA, exist_ok=True)
        for lad, _, ks in LADDERS:
            for k in ks:
                for m in MODES:
                    src = os.path.join(sys.argv[1], f'{m}_{lad}_k{k}', 'result.json')
                    if os.path.isfile(src):
                        shutil.copy(src, os.path.join(DATA, f'{m}_{lad}_k{k}.json'))
    lines, missing = [], []
    for i, (lad, title, ks) in enumerate(LADDERS):
        if i:
            lines.append('\\midrule')
        # (over the rung and the first router's columns, so that the rules between the routers run unbroken)
        lines.append(f'\\multicolumn{{5}}{{l@{{\\rsep}}}}{{\\emph{{{title}}}}}' + ' &' * 12 + ' \\\\')
        for k in ks:
            cells = [f'K{k}']
            for m in MODES:
                p = os.path.join(DATA, f'{m}_{lad}_k{k}.json')
                if not os.path.isfile(p):
                    missing.append(f'{m}_{lad}_k{k}')
                    cells += ['?'] * 4
                    continue
                r = json.load(open(p))
                cells += [str(r['vias']), str(r['mm']), str(r['open']), str(r['drc'])]
            lines.append(' & '.join(cells) + ' \\\\')
    # ...and, last in the Zynq's rows, its bus on its own board ('Full')
    cells = []
    for m in MODES:
        p = os.path.join(ROOT, 'data', 'board', f'{m}.json')
        if not os.path.isfile(p):
            missing.append(f'board {m}')
            cells += ['?'] * 4
            continue
        r = json.load(open(p))
        cells += [str(r['vias']), str(r['mm']), str(r['open']), str(r['drc'])]
    lines.append(' & '.join(['Full'] + cells) + ' \\\\')
    if missing:
        sys.exit('table1: no grade for ' + ', '.join(missing))
    out = os.path.join(ROOT, 'figs', 'table1.tex')
    open(out, 'w').write('% generated by gen/table1.py from data/table1 -- do not edit\n' + '\n'.join(lines) + '\n')
    print(f'wrote {out}')


if __name__ == '__main__':
    main()
